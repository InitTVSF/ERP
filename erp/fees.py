"""Fee module: dues, installments, challans, payments and receipts.

Tables live in SCHEMA; seed(conn) adds mock data and must be idempotent
(it runs on every start). See DOMAIN_MODULES in erp/db.py.

Amounts are whole rupees (INTEGER); dates are ISO strings. The "Pay now"
flow is a demo: it records a transaction but no money moves and no card
details are ever collected.
"""
import secrets
from datetime import date, datetime, timedelta

from erp import db

SCHEMA = """
-- One row per fee head per semester. `paid` is kept in step with
-- fee_payment_items so dues can be read without summing payments.
CREATE TABLE IF NOT EXISTS fee_heads (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    student_id   INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    semester     INTEGER NOT NULL,
    head         TEXT NOT NULL,
    amount       INTEGER NOT NULL,
    scholarship  INTEGER NOT NULL DEFAULT 0,
    paid         INTEGER NOT NULL DEFAULT 0,
    due_date     TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_fee_heads_student ON fee_heads(student_id);

-- Installment plan: each semester's net dues split into dated parts.
-- Status (paid/partial/pending/overdue) is derived from what was paid.
CREATE TABLE IF NOT EXISTS fee_installments (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    student_id      INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    installment_no  INTEGER NOT NULL,
    semester        INTEGER NOT NULL,
    due_date        TEXT NOT NULL,
    amount          INTEGER NOT NULL,
    UNIQUE (student_id, installment_no)
);

-- Every payment attempt. Only 'Success' rows have a receipt number.
CREATE TABLE IF NOT EXISTS fee_payments (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    student_id  INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    txn_id      TEXT NOT NULL UNIQUE,
    receipt_no  TEXT UNIQUE,
    paid_at     TEXT NOT NULL,
    mode        TEXT NOT NULL,
    amount      INTEGER NOT NULL,
    status      TEXT NOT NULL,
    remarks     TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_fee_payments_student ON fee_payments(student_id);

-- How a successful payment was split across fee heads (receipt lines).
CREATE TABLE IF NOT EXISTS fee_payment_items (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    payment_id  INTEGER NOT NULL REFERENCES fee_payments(id) ON DELETE CASCADE,
    head_id     INTEGER NOT NULL REFERENCES fee_heads(id) ON DELETE CASCADE,
    amount      INTEGER NOT NULL
);

-- Bank challans generated by the student for counter payment.
CREATE TABLE IF NOT EXISTS fee_challans (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    student_id   INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    ref_no       TEXT NOT NULL UNIQUE,
    created_at   TEXT NOT NULL,
    valid_until  TEXT NOT NULL,
    bank         TEXT NOT NULL,
    purpose      TEXT NOT NULL,
    amount       INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_fee_challans_student ON fee_challans(student_id);
"""

DEMO_MODE = "Online (demo)"
BANKS = ["Demo National Bank", "Demo Co-operative Bank"]
CHALLAN_VALID_DAYS = 15

# Fee heads charged every semester: (head, amount).
BASE_HEADS = [
    ("Tuition Fee", 72500),
    ("Examination Fee", 2500),
    ("Development Fee", 5000),
    ("Library & Lab Fee", 3000),
]
# Optional heads; a student gets at most one of these.
HOSTEL_HEAD = ("Hostel Fee", 45000)
TRANSPORT_HEAD = ("Transport Fee", 12000)

# Mock academic calendar: semester -> (first installment due, second due).
SEMESTER_DUES = {
    1: ("2025-08-01", "2025-10-15"),
    2: ("2026-01-15", "2026-03-15"),
    3: ("2026-08-01", "2026-11-15"),
}


def seed(conn):
    """Give every student without fee data a deterministic mock history.
    Also runs for students the admin adds later."""
    students = [r[0] for r in conn.execute(
        "SELECT id FROM students WHERE id NOT IN (SELECT DISTINCT student_id FROM fee_heads)")]
    for sid in students:
        _seed_student(conn, sid)


def _seed_student(conn, sid):
    # Vary by id (deterministic) so students don't all look the same.
    extra = (HOSTEL_HEAD, TRANSPORT_HEAD, None)[sid % 3]
    scholarship_pct = (0, 10, 0, 25)[sid % 4]
    inst_no = 0
    for sem, (due1, due2) in SEMESTER_DUES.items():
        heads = BASE_HEADS + ([extra] if extra else [])
        net = 0
        for head, amount in heads:
            schol = amount * scholarship_pct // 100 if head == "Tuition Fee" else 0
            conn.execute(
                "INSERT INTO fee_heads (student_id, semester, head, amount, scholarship, due_date)"
                " VALUES (?, ?, ?, ?, ?, ?)", (sid, sem, head, amount, schol, due1))
            net += amount - schol
        first = net // 2
        for due, amount in ((due1, first), (due2, net - first)):
            inst_no += 1
            conn.execute(
                "INSERT INTO fee_installments (student_id, installment_no, semester, due_date, amount)"
                " VALUES (?, ?, ?, ?, ?)", (sid, inst_no, sem, due, amount))

    # Semesters 1 and 2 are cleared; semester 3 is unpaid or half paid.
    _record_payment(conn, sid, _installments_total(conn, sid, 1, 2), "Net Banking",
                    "2025-07-28T11:42:10", "Semester 1 fee")
    _record_payment(conn, sid, _installments_total(conn, sid, 3), "UPI",
                    "2026-01-10T16:05:44", "Semester 2, installment 1")
    _record_failed(conn, sid, _installments_total(conn, sid, 4), "Net Banking",
                   "2026-03-12T19:20:03", "Payment not completed")
    _record_payment(conn, sid, _installments_total(conn, sid, 4), "Bank Challan",
                    "2026-03-13T12:10:31", "Semester 2, installment 2")
    if sid % 2:
        _record_payment(conn, sid, _installments_total(conn, sid, 5), "UPI",
                        "2026-07-29T10:15:00", "Semester 3, installment 1")


def _installments_total(conn, sid, *numbers):
    marks = ",".join("?" * len(numbers))
    return conn.execute(
        f"SELECT COALESCE(SUM(amount), 0) FROM fee_installments"
        f" WHERE student_id = ? AND installment_no IN ({marks})", (sid, *numbers)).fetchone()[0]


def _new_txn_id(when):
    return "TXN" + when.replace("-", "").replace(":", "").replace("T", "")[:14] + secrets.token_hex(3).upper()


def _record_failed(conn, sid, amount, mode, when, remarks):
    conn.execute(
        "INSERT INTO fee_payments (student_id, txn_id, paid_at, mode, amount, status, remarks)"
        " VALUES (?, ?, ?, ?, ?, 'Failed', ?)", (sid, _new_txn_id(when), when, mode, amount, remarks))


def _record_payment(conn, sid, amount, mode, when, remarks):
    """Record a successful payment and spread it over the oldest dues first.
    Caller guarantees amount <= outstanding. Returns the payment id."""
    cur = conn.execute(
        "INSERT INTO fee_payments (student_id, txn_id, paid_at, mode, amount, status, remarks)"
        " VALUES (?, ?, ?, ?, ?, 'Success', ?)", (sid, _new_txn_id(when), when, mode, amount, remarks))
    pid = cur.lastrowid
    conn.execute("UPDATE fee_payments SET receipt_no = ? WHERE id = ?", (f"RC-{when[:4]}-{pid:06d}", pid))
    left = amount
    for h in conn.execute(
            "SELECT id, amount - scholarship - paid AS bal FROM fee_heads"
            " WHERE student_id = ? AND amount - scholarship - paid > 0 ORDER BY semester, id", (sid,)):
        if left <= 0:
            break
        part = min(left, h["bal"])
        conn.execute("UPDATE fee_heads SET paid = paid + ? WHERE id = ?", (part, h["id"]))
        conn.execute("INSERT INTO fee_payment_items (payment_id, head_id, amount) VALUES (?, ?, ?)",
                     (pid, h["id"], part))
        left -= part
    return pid


# ---- Queries --------------------------------------------------------------

def fee_heads(student_id):
    """All fee heads with net payable and balance, oldest semester first."""
    with db.connect() as conn:
        return conn.execute(
            "SELECT *, amount - scholarship AS net, amount - scholarship - paid AS balance"
            " FROM fee_heads WHERE student_id = ? ORDER BY semester, id", (student_id,)).fetchall()


def dues_summary(student_id):
    """Totals across all semesters plus the current (latest) semester."""
    with db.connect() as conn:
        row = conn.execute(
            "SELECT COALESCE(SUM(amount), 0) AS amount, COALESCE(SUM(scholarship), 0) AS scholarship,"
            " COALESCE(SUM(paid), 0) AS paid, COALESCE(SUM(amount - scholarship - paid), 0) AS balance,"
            " MAX(semester) AS current_semester"
            " FROM fee_heads WHERE student_id = ?", (student_id,)).fetchone()
    return dict(row)


def installments(student_id, today=None):
    """Installment plan with a derived status. A semester's payments fill
    its installments in order, so 'paid' is cumulative within a semester."""
    today = (today or date.today()).isoformat()
    with db.connect() as conn:
        plan = conn.execute(
            "SELECT * FROM fee_installments WHERE student_id = ? ORDER BY installment_no",
            (student_id,)).fetchall()
        paid_by_sem = dict(conn.execute(
            "SELECT semester, SUM(paid) FROM fee_heads WHERE student_id = ? GROUP BY semester",
            (student_id,)).fetchall())
    rows = []
    for inst in plan:
        available = paid_by_sem.get(inst["semester"], 0)
        covered = min(available, inst["amount"])
        paid_by_sem[inst["semester"]] = available - covered
        balance = inst["amount"] - covered
        if balance == 0:
            status = "Paid"
        elif inst["due_date"] < today:
            status = "Overdue"
        elif covered:
            status = "Partially paid"
        else:
            status = "Pending"
        rows.append({**dict(inst), "paid": covered, "balance": balance, "status": status})
    return rows


def payment_options(student_id):
    """What the student may pay or put on a challan: {key: (label, amount)}.
    Amounts are always computed here, never taken from the form."""
    options = {}
    upcoming = next((i for i in installments(student_id) if i["balance"] > 0), None)
    if upcoming:
        options["installment"] = (
            f"Installment {upcoming['installment_no']} (Semester {upcoming['semester']})",
            upcoming["balance"])
    outstanding = dues_summary(student_id)["balance"]
    if outstanding > 0 and (not upcoming or outstanding != upcoming["balance"]):
        options["full"] = ("Full outstanding amount", outstanding)
    return options


def list_payments(student_id):
    with db.connect() as conn:
        return conn.execute(
            "SELECT * FROM fee_payments WHERE student_id = ? ORDER BY paid_at DESC, id DESC",
            (student_id,)).fetchall()


def get_receipt(student_id, payment_id):
    """(payment, items) for one of the student's own successful payments, or None."""
    with db.connect() as conn:
        payment = conn.execute(
            "SELECT * FROM fee_payments WHERE id = ? AND student_id = ? AND status = 'Success'",
            (payment_id, student_id)).fetchone()
        if payment is None:
            return None
        items = conn.execute(
            "SELECT h.semester, h.head, i.amount FROM fee_payment_items i"
            " JOIN fee_heads h ON h.id = i.head_id WHERE i.payment_id = ? ORDER BY h.semester, h.id",
            (payment_id,)).fetchall()
    return payment, items


def list_challans(student_id):
    with db.connect() as conn:
        return conn.execute(
            "SELECT * FROM fee_challans WHERE student_id = ? ORDER BY created_at DESC, id DESC",
            (student_id,)).fetchall()


def get_challan(student_id, challan_id):
    with db.connect() as conn:
        return conn.execute("SELECT * FROM fee_challans WHERE id = ? AND student_id = ?",
                            (challan_id, student_id)).fetchone()


# ---- Commands -------------------------------------------------------------

def pay_demo(student_id, option):
    """Mock online payment for one of payment_options(). Returns the new
    payment id, or None if the option isn't available (e.g. nothing due)."""
    with db.connect() as conn:
        # Take the write lock before reading the dues, so a double-clicked
        # button pays the next installment at most once.
        conn.execute("BEGIN IMMEDIATE")
        choice = payment_options(student_id).get(option)
        if choice is None:
            return None
        label, amount = choice
        return _record_payment(conn, student_id, amount, DEMO_MODE, db._now(), label)


def create_challan(student_id, option, bank):
    """Generate a bank challan; returns its id, or None for an invalid choice."""
    choice = payment_options(student_id).get(option)
    if choice is None or bank not in BANKS:
        return None
    label, amount = choice
    now = datetime.now()
    with db.connect() as conn:
        cur = conn.execute(
            "INSERT INTO fee_challans (student_id, ref_no, created_at, valid_until, bank, purpose, amount)"
            " VALUES (?, ?, ?, ?, ?, ?, ?)",
            (student_id, "CH" + now.strftime("%Y%m%d") + secrets.token_hex(3).upper(),
             now.isoformat(timespec="seconds"),
             (now.date() + timedelta(days=CHALLAN_VALID_DAYS)).isoformat(), bank, label, amount))
        return cur.lastrowid


# ---- Formatting helpers ---------------------------------------------------

def format_inr(value):
    """12345678 -> '1,23,45,678.00' (Indian digit grouping)."""
    value = int(value or 0)
    sign, s = ("-" if value < 0 else ""), str(abs(value))
    if len(s) > 3:
        head, tail = s[:-3], s[-3:]
        groups = []
        while len(head) > 2:
            groups.insert(0, head[-2:])
            head = head[:-2]
        s = ",".join([head] + groups if head else groups) + "," + tail
    return f"{sign}{s}.00"


_ONES = ("Zero One Two Three Four Five Six Seven Eight Nine Ten Eleven Twelve Thirteen"
         " Fourteen Fifteen Sixteen Seventeen Eighteen Nineteen").split()
_TENS = "_ _ Twenty Thirty Forty Fifty Sixty Seventy Eighty Ninety".split()


def amount_in_words(value):
    """45250 -> 'Rupees Forty Five Thousand Two Hundred Fifty Only'."""
    def below_100(n):
        return _ONES[n] if n < 20 else _TENS[n // 10] + ("" if n % 10 == 0 else " " + _ONES[n % 10])

    def below_1000(n):
        parts = []
        if n >= 100:
            parts.append(_ONES[n // 100] + " Hundred")
            n %= 100
        if n:
            parts.append(below_100(n))
        return " ".join(parts)

    n = int(value or 0)
    if n == 0:
        return "Rupees Zero Only"
    parts = []
    for size, name in ((10 ** 7, "Crore"), (10 ** 5, "Lakh"), (1000, "Thousand")):
        if n >= size:
            parts.append(f"{below_1000(n // size) if size == 10 ** 7 else below_100(n // size)} {name}")
            n %= size
    if n:
        parts.append(below_1000(n))
    return "Rupees " + " ".join(parts) + " Only"
