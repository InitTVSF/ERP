"""Student profile photos.

Files live in instance/uploads/photos (outside static/, so they are only
served through the apps' login-protected routes). The students.photo column
stores just the generated file name.
"""
import os
import secrets

from erp import db

PHOTO_DIR = os.path.join(os.path.dirname(db.DB_PATH), "uploads", "photos")
MAX_BYTES = 2 * 1024 * 1024
# Leading bytes of each allowed format -> extension we save it under.
SIGNATURES = [
    (b"\xff\xd8\xff", ".jpg"),
    (b"\x89PNG\r\n\x1a\n", ".png"),
    (b"RIFF", ".webp"),  # checked further below: bytes 8-12 must be WEBP
]
MIMETYPES = {".jpg": "image/jpeg", ".png": "image/png", ".webp": "image/webp"}


def _detect(head):
    for magic, ext in SIGNATURES:
        if head.startswith(magic):
            if ext == ".webp" and head[8:12] != b"WEBP":
                return None
            return ext
    return None


def save(file_storage):
    """Validate an uploaded werkzeug FileStorage and write it to disk.

    Returns the new file name. Raises ValueError with a user-facing message.
    The extension comes from the file's content, never from its name.
    """
    data = file_storage.read(MAX_BYTES + 1)
    if not data:
        raise ValueError("Choose an image to upload.")
    if len(data) > MAX_BYTES:
        raise ValueError("The photo must be 2 MB or smaller.")
    ext = _detect(data[:12])
    if ext is None:
        raise ValueError("Upload a JPG, PNG or WebP image.")
    os.makedirs(PHOTO_DIR, exist_ok=True)
    name = secrets.token_hex(16) + ext
    with open(os.path.join(PHOTO_DIR, name), "wb") as f:
        f.write(data)
    return name


def delete(name):
    """Remove a stored photo file; missing files are ignored."""
    if name:
        try:
            os.remove(path(name))
        except FileNotFoundError:
            pass
        except OSError:
            # On Windows a file being served at this moment can't be deleted.
            # A leftover file is harmless; failing the upload is not.
            pass


def path(name):
    # Names are always generated by save(); basename() guards against any other value.
    return os.path.join(PHOTO_DIR, os.path.basename(name))


def mimetype(name):
    return MIMETYPES.get(os.path.splitext(name)[1], "application/octet-stream")


def replace(student_id, file_storage):
    """Save a new photo for the student and delete the previous file."""
    student = db.get_student(student_id)
    name = save(file_storage)
    db.set_student_photo(student_id, name)
    delete(student["photo"] if student else "")
    return name


def remove(student_id):
    student = db.get_student(student_id)
    if student and student["photo"]:
        db.set_student_photo(student_id, "")
        delete(student["photo"])
