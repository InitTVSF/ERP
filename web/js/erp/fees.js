/** Mock online payment for one of payment_options(). Returns the new
 * payment id, or null if the option isn't available (e.g. nothing due).
 * (Requests run one at a time in the browser, so the Python version's
 * BEGIN IMMEDIATE lock isn't needed; the transaction keeps it atomic.) */
export function pay_demo(student_id, option) {
  return db.transaction(() => {
    const options = payment_options(student_id);
    const choice = Object.hasOwn(options, option) ? options[option] : null;
    if (choice === null) return null;
    const [label, amount] = choice;
    return _record_payment(db.connect(), student_id, amount, DEMO_MODE, nowISO(), label);
  });
}

/** Generate a bank challan; returns its id, or null for an invalid choice. */
export function create_challan(student_id, option, bank) {
  const options = payment_options(student_id);
  const choice = Object.hasOwn(options, option) ? options[option] : null;
  if (choice === null || !BANKS.includes(bank)) return null;
  const [label, amount] = choice;
  const now = PyDateTime.now();
  return db.connect().execute(
    "INSERT INTO fee_challans (student_id, ref_no, created_at, valid_until, bank, purpose, amount)" +
    " VALUES (?, ?, ?, ?, ?, ?, ?)",
    [student_id, "CH" + now.strftime("%Y%m%d") + tokenHex(3).toUpperCase(),
      now.isoformat(), now.date().addDays(CHALLAN_VALID_DAYS).isoformat(), bank, label, amount],
  ).lastrowid;
}

// ---- Formatting helpers ---------------------------------------------------

/** 12345678 -> '1,23,45,678.00' (Indian digit grouping). */
export function format_inr(value) {
  value = Math.trunc(Number(value || 0));
  const sign = value < 0 ? "-" : "";
  let s = String(Math.abs(value));
  if (s.length > 3) {
    let head = s.slice(0, -3);
    const tail = s.slice(-3);
    const groups = [];
    while (head.length > 2) {
      groups.unshift(head.slice(-2));
      head = head.slice(0, -2);
    }
    s = (head ? [head, ...groups] : groups).join(",") + "," + tail;
  }
  return `${sign}${s}.00`;
}

const _ONES = ("Zero One Two Three Four Five Six Seven Eight Nine Ten Eleven Twelve Thirteen" +
  " Fourteen Fifteen Sixteen Seventeen Eighteen Nineteen").split(" ");
const _TENS = "_ _ Twenty Thirty Forty Fifty Sixty Seventy Eighty Ninety".split(" ");

/** 45250 -> 'Rupees Forty Five Thousand Two Hundred Fifty Only'. */
export function amount_in_words(value) {
  const below_100 = (n) => (n < 20 ? _ONES[n] : _TENS[Math.floor(n / 10)] + (n % 10 === 0 ? "" : " " + _ONES[n % 10]));
  const below_1000 = (n) => {
    const parts = [];
    if (n >= 100) {
      parts.push(_ONES[Math.floor(n / 100)] + " Hundred");
      n %= 100;
    }
    if (n) parts.push(below_100(n));
    return parts.join(" ");
  };

  let n = Math.trunc(Number(value || 0));
  if (n === 0) return "Rupees Zero Only";
  const parts = [];
  for (const [size, name] of [[10 ** 7, "Crore"], [10 ** 5, "Lakh"], [1000, "Thousand"]]) {
    if (n >= size) {
      const q = Math.floor(n / size);
      parts.push(`${size === 10 ** 7 ? below_1000(q) : below_100(q)} ${name}`);
      n %= size;
    }
  }
  if (n) parts.push(below_1000(n));
  return "Rupees " + parts.join(" ") + " Only";
}
